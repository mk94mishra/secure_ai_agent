# ============================================================
# STRUCTURED RISK MODEL
# ============================================================

risk_model = llm.with_structured_output(
    RiskAssessment
)


# ============================================================
# RISK CHAIN
# ============================================================

risk_chain = (
    risk_prompt
    |
    risk_model
)


# ============================================================
# HELPER: APPROVAL RULE
# ============================================================

def approval_required_for_risk(
    risk: str
) -> bool:
    """
    Application-level security rule.

    HIGH and CRITICAL always require approval.
    """

    return risk in {
        "HIGH",
        "CRITICAL"
    }


# ============================================================
# RISK NODE
# ============================================================

async def risk_node(
    state: AgentState
):
    """
    Run evidence-aware security risk assessment.
    """

    # --------------------------------------------------------
    # Read state
    # --------------------------------------------------------

    alert = state.get(
        "alert",
        {}
    )

    query = state.get(
        "query",
        ""
    )

    context = state.get(
        "context",
        []
    )

    findings = state.get(
        "findings",
        []
    )

    evidence = state.get(
        "evidence",
        []
    )

    # --------------------------------------------------------
    # Run structured risk assessment
    # --------------------------------------------------------

    assessment = await risk_chain.ainvoke(
        {
            "alert": alert,

            "query": query,

            "context": context,

            "findings": findings,

            "evidence": evidence,
        }
    )

    # --------------------------------------------------------
    # IMPORTANT SECURITY CONTROL
    # --------------------------------------------------------
    #
    # Do NOT trust:
    #
    # assessment.requires_approval
    #
    # Instead enforce the rule in application code.
    #

    requires_approval = (
        approval_required_for_risk(
            assessment.risk
        )
    )

    # --------------------------------------------------------
    # Build final response
    # --------------------------------------------------------

    final_response = (
        f"Risk: {assessment.risk}\n"
        f"Confidence: "
        f"{assessment.confidence:.2f}\n\n"
        f"Summary:\n"
        f"{assessment.summary}\n\n"
        f"Recommended Action:\n"
        f"{assessment.recommended_action}"
    )

    # --------------------------------------------------------
    # Return state
    # --------------------------------------------------------

    return {
        "risk": assessment.risk,

        "confidence": assessment.confidence,

        "findings": assessment.findings,

        "recommended_action":
            assessment.recommended_action,

        "requires_approval":
            requires_approval,

        "final_response":
            final_response,
    }