from typing import Literal

from langchain_core.prompts import ChatPromptTemplate
from pydantic import BaseModel, Field

from agents.llm import llm
from agents.state import AgentState


# ============================================================
# RISK ASSESSMENT MODEL
# ============================================================

class RiskAssessment(BaseModel):
    """
    Structured output generated by the Risk Agent.
    """

    risk: Literal[
        "LOW",
        "MEDIUM",
        "HIGH",
        "CRITICAL"
    ]

    confidence: float = Field(
        ge=0.0,
        le=1.0,
        description=(
            "Confidence in the risk assessment "
            "between 0 and 1."
        )
    )

    summary: str = Field(
        description=(
            "Concise summary explaining the "
            "security risk."
        )
    )

    findings: list[str] = Field(
        description=(
            "Important findings supporting "
            "the risk assessment."
        )
    )

    recommended_action: str = Field(
        description=(
            "Recommended next action for the "
            "security team."
        )
    )

    requires_approval: bool = Field(
        description=(
            "Whether human approval is recommended. "
            "The application will enforce this separately."
        )
    )


